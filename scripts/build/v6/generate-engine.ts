import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { bundleEngine, BundleEngineResult } from './bundle-engine';
import { allAntdComponentNames } from './components';
import { joinTemplate, normalizeCssVarRootCls, partitionBlocks } from './css-postprocess';
import { extractAntdCss } from './extract-styles';
import { generateTypes } from './generate-types';
import { generatedDir } from './paths';

export { generatedDir } from './paths';

/** Runs BEFORE the ng-packagr build: the library source imports these bundles. */
export async function generateEngine(): Promise<BundleEngineResult> {
  const sizes = await bundleEngine({ outDir: generatedDir, antdNames: allAntdComponentNames() });
  await generateTypes(generatedDir);
  await writeTestCss(generatedDir);
  return sizes;
}

/** Writes `generated/test-css.ts` (gitignored) so browser specs can install real antd CSS without a build. */
async function writeTestCss(dir: string): Promise<void> {
  const raw = extractAntdCss({ includes: allAntdComponentNames(), key: 'nz-root' });
  const template = normalizeCssVarRootCls(joinTemplate(partitionBlocks(raw, 'nz-root').template));
  const renderer = await import('../../../components/core/theme/render-theme-css');
  const tokens = await renderer.renderThemeCss({}, ':root');
  const patch = readFileSync(path.resolve(__dirname, '../../../components/style/v6/patch.css'), 'utf8');
  const selectPatch = readFileSync(path.resolve(__dirname, '../../../components/select/style/v6/patch.css'), 'utf8');
  const spinPatch = readFileSync(path.resolve(__dirname, '../../../components/spin/style/v6/patch.css'), 'utf8');
  writeFileSync(
    path.join(dir, 'test-css.ts'),
    [
      '/* Generated by scripts/build/v6/generate-engine.ts for unit tests. Do not edit. */',
      `export const V6_TEMPLATE_CSS = ${JSON.stringify(template)};`,
      `export const V6_TOKENS_DEFAULT_CSS = ${JSON.stringify(tokens)};`,
      `export const V6_PATCH_CSS = ${JSON.stringify(`${patch}\n${selectPatch}\n${spinPatch}`)};`,
      ''
    ].join('\n')
  );
}
